-- DESCRIPTION: Calculating Correlation and Linear Regression in pure MySQL
-- Note: MySQL doesn't have a built-in CORR() function like Postgres, 
-- so I had to use the actual math formulas using SUM and AVG.
-- ==========================================================

-- ----------------------------------------------------------
-- 1. PEARSON CORRELATION COEFFICIENT
-- Question: Is there a correlation between the Discount given 
-- and the Quantity purchased? (Do bigger discounts = more items bought?)
-- Formula: r = (N*Sum(xy) - Sum(x)*Sum(y)) / sqrt([N*Sum(x^2) - Sum(x)^2] * [N*Sum(y^2) - Sum(y)^2])
-- ----------------------------------------------------------
SELECT 
    -- Using a subquery to get the final division
    (
        (COUNT(*) * SUM(oi.Discount * oi.Quantity)) - (SUM(oi.Discount) * SUM(oi.Quantity))
    ) / 
    SQRT(
        (COUNT(*) * SUM(POW(oi.Discount, 2)) - POW(SUM(oi.Discount), 2)) * 
        (COUNT(*) * SUM(POW(oi.Quantity, 2)) - POW(SUM(oi.Quantity), 2))
    ) AS Correlation_Coefficient
FROM OrderItems oi;

-- ----------------------------------------------------------
-- 2. LINEAR REGRESSION (Slope and Intercept)
-- Let's build a simple linear regression model: y = mx + c
-- Where y = Quantity (Dependent), and x = Discount (Independent).
-- Formula for Slope (m): (N*Sum(xy) - Sum(x)*Sum(y)) / (N*Sum(x^2) - Sum(x)^2)
-- Formula for Intercept (c): Avg(y) - (Slope * Avg(x))
-- ----------------------------------------------------------
WITH RegressionMath AS (
    SELECT 
        COUNT(*) AS N,
        SUM(oi.Discount) AS SumX,
        SUM(oi.Quantity) AS SumY,
        SUM(oi.Discount * oi.Quantity) AS SumXY,
        SUM(POW(oi.Discount, 2)) AS SumX2,
        AVG(oi.Discount) AS AvgX,
        AVG(oi.Quantity) AS AvgY
    FROM OrderItems oi
)
SELECT 
    -- Calculating the Slope (m)
    (
        (N * SumXY) - (SumX * SumY)
    ) / 
    (
        (N * SumX2) - POW(SumX, 2)
    ) AS Regression_Slope,
    
    -- Calculating the Intercept (c)
    AvgY - (
        (
            ((N * SumXY) - (SumX * SumY)) / 
            ((N * SumX2) - POW(SumX, 2))
        ) * AvgX
    ) AS Regression_Intercept
    
FROM RegressionMath;

